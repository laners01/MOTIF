package com.ssafy.motif.media.encode;

/**
 * 화질 사다리의 한 단 (ADR-0010 D1).
 *
 * <p><b>{@code width} 는 짧은 변이다 — 가로 픽셀이 아니다.</b> 이름이 {@code width}
 * 인 것은 세로 영상만 받던 시절의 잔재이고, 2026-09-17 부터 가로도 처리한다.
 * 세로면 짧은 변이 가로폭, 가로면 세로높이다 — 어느 쪽인지는 {@code HlsPackager} 가
 * 원본을 재서 정한다. 전체화면 세로 재생에서는 <b>화면 가로폭에 맞닿는 변</b>이라
 * 이 값이 곧 체감 화질을 결정한다 — {@code 720p} 단은 세로에서 720×1280,
 * 가로에서 1280×720 이고 화소 수는 921,600 으로 같다.
 *
 * <p>화소 수가 같으므로 <b>{@code maxrateKbps} 는 방향과 무관하게 같은 값을 쓴다.</b>
 * 가로 전용 사다리를 따로 두면 같은 {@code 720p} 가 두 뜻이 돼 마스터 재생목록의
 * {@code RESOLUTION} 으로 화질을 고르는 ABR 이 어긋난다.
 *
 * <p>이름도 이 값을 가리킨다. 인스타·틱톡이 세로 영상을 부르는 방식과 같다 —
 * 남들이 말하는 세로 "1080p" 는 1080×1920 이다.
 *
 * <p><b>2026-09-14 이전에는 기준이 프레임 높이(긴 변)였다.</b> {@code scale=-2:720}
 * 이라 {@code 720p} 가 406×720 이었고, 1080px 화면에서 2.7배 확대돼 보였다.
 * 최상단조차 608×1080 으로 원본(1080×1920)보다 작아 원본 화질을 준 적이 없다.
 * 원래 주석은 "짧은 변"이라고 적어놓고 예시는 406×720 을 들어 서술과 코드가
 * 어긋나 있었다 — 주석 쪽이 의도였고 코드를 거기에 맞췄다.
 *
 * @param tag         S3 키·재생목록 경로에 쓰는 이름 ({@code 720p})
 * @param width       <b>짧은 변</b> 픽셀. 세로 원본이면 {@code scale=width:-2},
 *                    가로 원본이면 {@code scale=-2:width} 로 들어가고 긴 변은
 *                    비율에 맞춰 따라온다 ({@code HlsPackager.scaleShortSide})
 * @param maxrateKbps 비트레이트 상한. CRF 만 쓰면 내용에 따라 원본 대비 15~69% 로
 *                    4.6배 편차가 난다 — ABR 이 재생목록의 {@code BANDWIDTH} 로
 *                    화질을 고르므로 사다리가 예측 가능해야 한다 (ADR-0010 D4)
 */
public record Rendition(String tag, int width, int maxrateKbps) {

    /**
     * 채택 사다리 (ADR-0010 D1). 낮은 화질부터 — 마스터 재생목록 순서와 같다.
     *
     * <p>2026-09-14 에 3단으로 늘리고 기준을 짧은 변으로 바꿨다. 최상단이 원본
     * 해상도(1080×1920)와 같아져 <b>처음으로 원본 화질을 그대로 내보낸다.</b>
     * 2026-09-17 에 그 "짧은 변" 을 방향과 무관하게 일반화해 가로 원본(모티프 에셋
     * 미리보기)도 같은 사다리를 탄다 — 값은 건드리지 않았다.
     * 대역폭이 모자라면 ABR 이 720p·480p 로 내려가면 된다 — 그러라고 사다리를 둔다.
     *
     * <p>상한값은 실측 기준이다. 같은 원본(1080×1920, 9초)을 {@code -maxrate} 없이
     * CRF 26 으로만 뽑았을 때의 자연 비트레이트가 480p 905 · 720p 1523 ·
     * 1080p 2641 kbps 였고, 기존 사다리가 쓰던 여유 배수(자연값의 약 1.55배)를
     * 그대로 적용했다. 상한은 목표가 아니라 뚜껑이다 — 움직임이 많은 영상이
     * 여기에 닿는다.
     *
     * <p><b>원본보다 큰 단은 실행 시점에 걸러진다</b>({@code HlsPackager.ladderFor}).
     * 여기 있다고 항상 만들어지는 것이 아니다.
     */
    public static final java.util.List<Rendition> LADDER = java.util.List.of(
            new Rendition("480p", 480, 1400),
            new Rendition("720p", 720, 2400),
            new Rendition("1080p", 1080, 4100));

    /** {@code -bufsize} 는 상한의 2배로 둔다 — 순간 변동을 흡수하되 평균은 상한에 묶인다. */
    public int bufsizeKbps() {
        return maxrateKbps * 2;
    }
}
