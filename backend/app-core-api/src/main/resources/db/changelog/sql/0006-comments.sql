--changeset claude:0006-01-create-challenge-comments
--comment 챌린지 댓글. PK BIGINT
CREATE TABLE challenge_comments (
    challenge_comment_seq BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    challenge_seq         INTEGER     NOT NULL,
    user_seq              INTEGER     NOT NULL,
    parent_comment_seq    BIGINT      NULL,
    content               TEXT        NOT NULL,
    like_count            INTEGER     NOT NULL DEFAULT 0,
    is_deleted            BOOLEAN     NOT NULL DEFAULT FALSE,
    reg_dttm              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm              TIMESTAMPTZ NULL,
    mod_usr_seq           INTEGER     NULL,
    CONSTRAINT pk_challenge_comments PRIMARY KEY (challenge_comment_seq),
    CONSTRAINT ck_challenge_comments_like_count CHECK (like_count >= 0),
    CONSTRAINT ck_challenge_comments_not_self CHECK (
        parent_comment_seq IS NULL OR parent_comment_seq <> challenge_comment_seq
    ),
    CONSTRAINT fk_challenge_comments_challenge FOREIGN KEY (challenge_seq)
        REFERENCES challenges (challenge_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_challenge_comments_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_challenge_comments_parent FOREIGN KEY (parent_comment_seq)
        REFERENCES challenge_comments (challenge_comment_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_challenge_comments_mod_usr FOREIGN KEY (mod_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_challenge_comments_target ON challenge_comments (challenge_seq, is_deleted, reg_dttm DESC);
CREATE INDEX idx_challenge_comments_parent ON challenge_comments (parent_comment_seq);
CREATE INDEX idx_challenge_comments_user   ON challenge_comments (user_seq, reg_dttm DESC);
--rollback DROP TABLE challenge_comments;

