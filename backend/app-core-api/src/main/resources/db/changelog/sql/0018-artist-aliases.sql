--changeset claude:0018-04-backfill-aliases
--comment 이미 등록된 비삭제 아티스트·그룹의 현재 이름을 ko 별칭으로 채운다. 이게 없으면 배포 직후 검색이 전건 0이다
INSERT INTO artist_aliases (artist_seq, language_code, alias, reg_usr_seq)
SELECT a.artist_seq, 'ko', u.nickname, a.reg_usr_seq
  FROM artists a
  JOIN users u ON u.user_seq = a.user_seq
 WHERE a.is_deleted = FALSE;

INSERT INTO group_aliases (group_seq, language_code, alias, reg_usr_seq)
SELECT g.group_seq, 'ko', g.group_name, g.reg_usr_seq
  FROM artist_groups g
 WHERE g.is_deleted = FALSE;
