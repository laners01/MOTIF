-- 별칭은 "찾기" 전용이다. 응답에 실리는 이름은 여전히 users.nickname 이다 — 별칭을 표시에
-- 쓰면 같은 아티스트가 질의에 따라 다른 이름으로 보인다(ADR-0014 D1).
--
-- 아티스트와 그룹을 한 테이블로 합치지 않는다. artist_seq FK 하나로는 그룹을 못 가리키고,
-- 무엇보다 "이 매치가 그룹 매치였다" 는 사실이 있어야 §5.2 가 그 그룹의 멤버를 결과에 펼치고
-- 본인 매치보다 뒤로 정렬한다. 테이블을 갈라 두면 그 판정이 조회 구조에서 공짜로 나온다.
--
-- UNIQUE 를 두지 않는다 — 한 언어에 표기 변형이 여럿이다(aespa·æspa, 활동명·본명).
-- 중복 입력도 막지 않는다. §5.2 가 artist_seq 로 중복을 제거한다.
--
-- 소프트 삭제 칼럼이 없다. 아티스트·그룹을 소프트 삭제해도 별칭 행은 그대로 두고 조회가
-- 조인에서 is_deleted = FALSE 로 거른다 — 복구하면 별칭이 살아 돌아온다. 어드민이 직접
-- 지우는 것(어드민 §3.5.9)만 하드 삭제다.
