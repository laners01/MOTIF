--changeset claude:0018-01-create-artist-aliases
--comment 아티스트 별칭. 표시가 아니라 검색 대상이다. mod_usr_seq 는 artists 와 같은 이유로 두지 않는다
CREATE TABLE artist_aliases (
    alias_seq     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    artist_seq    INTEGER      NOT NULL,
    language_code CHAR(2)      NOT NULL,
    alias         VARCHAR(100) NOT NULL,
    reg_usr_seq   INTEGER      NOT NULL,
    reg_dttm      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ  NULL,
    CONSTRAINT pk_artist_aliases PRIMARY KEY (alias_seq),
    CONSTRAINT fk_artist_aliases_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artist_aliases_reg_usr FOREIGN KEY (reg_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_artist_aliases_artist ON artist_aliases (artist_seq);
--rollback DROP TABLE artist_aliases;

--changeset claude:0018-02-create-group-aliases
--comment 그룹 별칭. §41 과 같은 구조이며 대상만 다르다
CREATE TABLE group_aliases (
    alias_seq     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    group_seq     INTEGER      NOT NULL,
    language_code CHAR(2)      NOT NULL,
    alias         VARCHAR(100) NOT NULL,
    reg_usr_seq   INTEGER      NOT NULL,
    reg_dttm      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ  NULL,
    CONSTRAINT pk_group_aliases PRIMARY KEY (alias_seq),
    CONSTRAINT fk_group_aliases_group FOREIGN KEY (group_seq)
        REFERENCES artist_groups (group_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_group_aliases_reg_usr FOREIGN KEY (reg_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_group_aliases_group ON group_aliases (group_seq);
--rollback DROP TABLE group_aliases;

