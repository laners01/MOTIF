--changeset claude:0019-02-participant-edited-columns
--comment 편집본 3키를 슬롯 행으로. 영상·첫 장면은 짝이고 선택 화면 이미지는 따로 채울 수 있다
ALTER TABLE challenge_participants
    ADD COLUMN edited_challenge_key VARCHAR(255) NULL,
    ADD COLUMN initial_scene_key    VARCHAR(255) NULL,
    ADD COLUMN preview_image_key    VARCHAR(255) NULL,
    ADD COLUMN reg_dttm             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN mod_dttm             TIMESTAMPTZ  NULL,
    ADD CONSTRAINT ck_challenge_participants_edited CHECK (
        (edited_challenge_key IS NULL AND initial_scene_key IS NULL)
        OR (edited_challenge_key IS NOT NULL AND initial_scene_key IS NOT NULL)
    );
UPDATE challenge_participants p
SET edited_challenge_key = e.video_key,
    initial_scene_key    = e.initial_scene_key,
    preview_image_key    = e.preview_image_key
FROM edited_challenges e
WHERE e.challenge_seq = p.challenge_seq
  AND e.participant_mask = (1 << p.slot_order);
--rollback ALTER TABLE challenge_participants DROP CONSTRAINT ck_challenge_participants_edited, DROP COLUMN edited_challenge_key, DROP COLUMN initial_scene_key, DROP COLUMN preview_image_key, DROP COLUMN reg_dttm, DROP COLUMN mod_dttm;

--changeset claude:0019-03-composite-jobs-retarget
--comment 잡이 가리키는 대상을 편집본 행 → 슬롯 행으로. 조합 편집본을 쓰던 잡은 참조를 끊는다(무교체로 읽힌다)
ALTER TABLE composite_jobs DROP CONSTRAINT fk_composite_jobs_edited_challenge;
ALTER TABLE composite_jobs DROP CONSTRAINT ck_composite_jobs_type_shape;
ALTER TABLE composite_jobs RENAME COLUMN edited_challenge_seq TO challenge_participant_seq;
UPDATE composite_jobs j
SET challenge_participant_seq = p.challenge_participant_seq
FROM edited_challenges e
         JOIN challenge_participants p
              ON p.challenge_seq = e.challenge_seq
                  AND (1 << p.slot_order) = e.participant_mask
WHERE e.edited_challenge_seq = j.challenge_participant_seq;
UPDATE composite_jobs j
SET challenge_participant_seq = NULL
WHERE j.challenge_participant_seq IS NOT NULL
  AND NOT EXISTS (SELECT 1
                  FROM challenge_participants p
                  WHERE p.challenge_participant_seq = j.challenge_participant_seq);
ALTER TABLE composite_jobs
    ADD CONSTRAINT fk_composite_jobs_challenge_participant FOREIGN KEY (challenge_participant_seq)
        REFERENCES challenge_participants (challenge_participant_seq) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_composite_jobs_type_shape CHECK (
        (job_type = 'CHALLENGE' AND challenge_seq IS NOT NULL AND asset_seq IS NULL)
        OR (job_type = 'MOTIF' AND asset_seq IS NOT NULL AND challenge_seq IS NULL
            AND challenge_participant_seq IS NULL)
    );
--rollback ALTER TABLE composite_jobs DROP CONSTRAINT ck_composite_jobs_type_shape, DROP CONSTRAINT fk_composite_jobs_challenge_participant;
--rollback ALTER TABLE composite_jobs RENAME COLUMN challenge_participant_seq TO edited_challenge_seq;
