-- 0019 편집본을 슬롯 행으로 합친다 — edited_challenges 삭제
-- 명세: backend/docs/erd/MOTIF_DB_SPEC_v0_15.md §13·§14 (v0.16 변경)
--
-- 스키마 정리가 아니라 모델 변경이다. 지금까지 편집본은 "지운 슬롯 조합" 단위였고
-- participant_mask 가 비트 OR 합이라 3인 챌린지면 {0}·{1}·{0,1}·{0,1,2} … 가 각각 한
-- 행이었다. 앞으로는 **참가자 1명당 편집본 1개**다 — 사용자가 고르는 것은 "함께할
-- 아티스트 한 명" 이고, 2명 이상을 한 번에 지운 편집본은 만들지 않는다.
--
-- 그래서 조합을 표현하던 마스크 칼럼이 사라지고 slot_order(화면 좌→우, 0부터)가 그
-- 자리를 대신한다. 마스크가 필요한 곳은 AI 접수 페이로드 하나뿐이고 1 << slot_order
-- 로 파생된다 — 계약은 그대로다(AI 서버 명세 §3.2).
--
-- 대리키를 새로 세우는 이유는 composite_jobs 가 편집본을 가리키고 있기 때문이다.
-- (challenge_seq, artist_seq) 복합키로는 잡 행이 칼럼 2개로 참조해야 한다.
--
-- 기존 행은 살릴 수 있는 만큼 살린다 — 슬롯은 전부(앵커 포함), 편집본은 단일 비트인
-- 것만. 조합 편집본은 새 모델에 자리가 없어 옮기지 않는다.
--
-- (주석 줄을 "changeset" 으로 시작하지 않는다 — formatted SQL 파서가 선언으로 읽는다.)

