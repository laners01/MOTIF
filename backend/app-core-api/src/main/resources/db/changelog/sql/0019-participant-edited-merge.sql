--comment 복합키 → 대리키, participant_mask → slot_order. 마스크는 단일 비트라 지수가 곧 순서다
ALTER TABLE challenge_participants
    ADD COLUMN challenge_participant_seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN slot_order INTEGER NULL;
