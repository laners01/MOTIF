--changeset claude:0003-01-create-artists
--comment users.role='ARTIST' 사용자의 도메인 확장. subscriber_count 는 거울 카운터
CREATE TABLE artists (
    artist_seq         INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    user_seq           INTEGER      NOT NULL,
    group_seq          INTEGER      NULL,
    company_seq        INTEGER      NOT NULL,
    motif_bg_image_key VARCHAR(255) NULL,
    bio                TEXT         NULL,
    subscriber_count   INTEGER      NOT NULL DEFAULT 0,
    reg_usr_seq        INTEGER      NOT NULL,
    is_deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_dttm           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm           TIMESTAMPTZ  NULL,
    CONSTRAINT pk_artists PRIMARY KEY (artist_seq),
    CONSTRAINT uq_artists_user UNIQUE (user_seq),
    CONSTRAINT ck_artists_subscriber_count CHECK (subscriber_count >= 0),
    CONSTRAINT fk_artists_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artists_group FOREIGN KEY (group_seq)
        REFERENCES artist_groups (group_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artists_company FOREIGN KEY (company_seq)
        REFERENCES companies (company_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artists_reg_usr FOREIGN KEY (reg_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_artists_group   ON artists (group_seq, is_deleted);
CREATE INDEX idx_artists_company ON artists (company_seq, is_deleted);
--rollback DROP TABLE artists;

--changeset claude:0003-02-create-subscriptions
--comment 무료 팔로우. 해제 시 하드 삭제하는 복합 PK 관계 테이블
CREATE TABLE subscriptions (
    user_seq   INTEGER     NOT NULL,
    artist_seq INTEGER     NOT NULL,
    reg_dttm   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_subscriptions PRIMARY KEY (user_seq, artist_seq),
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_subscriptions_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_subscriptions_artist ON subscriptions (artist_seq);
--rollback DROP TABLE subscriptions;

--changeset claude:0003-03-grant-subscriptions-select-notif
--comment 알림 팬아웃 예외 — notif_app 에 읽기 전용 SELECT 만 부여. 교차 스키마 FK 는 두지 않는다
GRANT SELECT ON subscriptions TO notif_app;
