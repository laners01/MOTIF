--changeset claude:0001-01-create-countries
--comment 국가 판매 설정. reg_usr_seq NULL = 시스템(마이그레이션 시드) 생성 (v0.14 R9)
CREATE TABLE countries (
    country_seq  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    country_code CHAR(2)      NOT NULL,
    country_name VARCHAR(100) NOT NULL,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    reg_usr_seq  INTEGER      NULL,
    reg_dttm     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq  INTEGER      NULL,
    mod_dttm     TIMESTAMPTZ  NULL,
    CONSTRAINT pk_countries PRIMARY KEY (country_seq),
    CONSTRAINT uq_countries_code UNIQUE (country_code),
    CONSTRAINT ck_countries_code_format CHECK (country_code ~ '^[A-Z]{2}$')
);
--rollback DROP TABLE countries;

--changeset claude:0001-02-create-oauth-providers
--comment OAuth 제공자 마스터
CREATE TABLE oauth_providers (
    provider_seq  INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    provider_code VARCHAR(20) NOT NULL,
    reg_dttm      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_oauth_providers PRIMARY KEY (provider_seq),
    CONSTRAINT uq_oauth_providers_code UNIQUE (provider_code),
    CONSTRAINT ck_oauth_providers_code_format CHECK (provider_code ~ '^[A-Z][A-Z0-9_]{1,19}$')
);
--rollback DROP TABLE oauth_providers;

--changeset claude:0001-03-create-companies
--comment 소속사. 활성 회사명만 UNIQUE(부분 UNIQUE)
CREATE TABLE companies (
    company_seq  INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    company_name VARCHAR(50) NOT NULL,
    reg_usr_seq  INTEGER     NOT NULL,
    is_deleted   BOOLEAN     NOT NULL DEFAULT FALSE,
    reg_dttm     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq  INTEGER     NULL,
    mod_dttm     TIMESTAMPTZ NULL,
    CONSTRAINT pk_companies PRIMARY KEY (company_seq)
);
CREATE UNIQUE INDEX uq_companies_name_active
    ON companies (company_name)
 WHERE is_deleted = FALSE;
--rollback DROP INDEX uq_companies_name_active;
--rollback DROP TABLE companies;

--changeset claude:0001-04-create-artist-groups
--comment 아티스트 그룹. group_name 은 중복 허용(pg_trgm 검색 대상 — 0012)
CREATE TABLE artist_groups (
    group_seq   INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    company_seq INTEGER     NOT NULL,
    group_name  VARCHAR(50) NOT NULL,
    reg_usr_seq INTEGER     NOT NULL,
    is_deleted  BOOLEAN     NOT NULL DEFAULT FALSE,
    reg_dttm    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq INTEGER     NULL,
    mod_dttm    TIMESTAMPTZ NULL,
    CONSTRAINT pk_artist_groups PRIMARY KEY (group_seq),
    CONSTRAINT fk_artist_groups_company FOREIGN KEY (company_seq)
        REFERENCES companies (company_seq) ON DELETE RESTRICT
);
