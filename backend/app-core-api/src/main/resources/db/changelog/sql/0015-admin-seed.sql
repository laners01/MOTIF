--
-- ── 해시를 파일에 적지 않는다 ────────────────────────────────────────────────
-- ${adminSeedHash} 는 Liquibase property 다. application.yml 의
--   spring.liquibase.parameters.adminSeedHash
-- 가 환경변수 ADMIN_SEED_HASH 에서 받아 넘긴다. 해시를 여기 박으면 리포지토리에
-- 자격증명이 들어가고, 회전하려면 배포된 changeSet 을 고쳐야 해서 회전 자체가
-- 막힌다(배포된 changeSet 은 수정 금지 — 0013 헤더).
--
-- 해시 생성(오프라인, 평문·해시 모두 팀 비밀 저장소에만 — 부록 B 1항):
--   htpasswd -bnBC 10 "" '평문' | tr -d ':\n'
-- cost 는 10 이어야 한다 — AdminSecurityConfig 의 BCryptPasswordEncoder(10) 와 같은 값.
--
-- ── 순서: users(ADMIN) → admins ─────────────────────────────────────────────
-- admins.user_seq 는 0014 에서 NOT NULL FK 가 됐다. users 행이 먼저 있어야 한다.
-- IDENTITY 는 GENERATED BY DEFAULT 라 PK 를 명시하지 않는다 — 명시값은 시퀀스를
-- 전진시키지 않아 이후 INSERT 가 충돌한다(0013 헤더, v0.15 운영 기준).
--
-- ── validCheckSum ANY 가 붙은 이유 (실측으로 확인한 함정) ───────────────────
-- Liquibase 는 property 치환이 <끝난> SQL 로 체크섬을 계산한다. 그래서 해시 값이
-- 바뀌면 이미 적용된 이 changeSet 의 체크섬이 달라지고, 다음 기동에서
--   ValidationFailedException: 0015-02-seed-admin was: 9:c79a… but is now: 9:abeb…
-- 로 <애플리케이션이 아예 뜨지 않는다>. 2026-09-13 실측.
--
-- 즉 ADMIN_SEED_HASH 회전이 곧 장애가 된다. 비밀값을 못 바꾸는 설계는 안 된다.
-- ANY 를 붙여 이 항목만 체크섬 검증에서 뺀다 — 값이 달라지는 것이 정상인
-- 자리이기 때문이다.
--
-- (주석 줄이 '--' 바로 뒤에 changeSet 으로 시작하면 파서가 선언으로 읽고 깨진다.
--  이 파일에서 실제로 한 번 밟았다 — 줄바꿈 위치를 바꿔 피한다.)
--
-- 대가: 이 파일의 SQL 을 나중에 수정해도 경고 없이 통과한다. 그래서 <고치지 않는다>.
-- 아래 "재실행·추가" 규칙이 그 전제다.
--
-- 주의: 해시를 바꿔도 이미 적용된 changeSet 은 다시 실행되지 않는다 — DB 의
-- 비밀번호는 그대로다. 실제 회전은 새 번호의 UPDATE changeSet 이 한다.
--
-- ── 재실행·추가 ─────────────────────────────────────────────────────────────
-- 어드민을 더 넣거나 내보낼 때는 이 파일을 고치지 않고 새 번호 changeSet 을 쓴다.
-- 퇴장은 DELETE 가 아니라 is_active=FALSE 다 — ADMIN users 행에 감사 참조
-- (reg_usr_seq 등)가 남아 있어 지울 수 없다(부록 B 4항).

--changeset claude:0015-01-seed-admin-user
--comment 감사 주체가 될 users(ADMIN) 행. 닉네임은 0014 백필과 같은 'admin_' 규칙
INSERT INTO users (nickname, role) VALUES ('admin_admin', 'ADMIN');
--rollback DELETE FROM users WHERE nickname = 'admin_admin' AND role = 'ADMIN';

--changeset claude:0015-02-seed-admin
--comment 부록 B 2항. user_seq 는 방금 만든 ADMIN 행에서 가져온다
--validCheckSum ANY
INSERT INTO admins (login_id, password_hash, name, user_seq)
SELECT 'admin', '${adminSeedHash}', '운영자', u.user_seq
FROM users u
WHERE u.nickname = 'admin_admin' AND u.role = 'ADMIN';
--rollback DELETE FROM admins WHERE login_id = 'admin';
