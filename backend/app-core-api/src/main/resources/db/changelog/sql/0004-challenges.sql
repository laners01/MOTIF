--changeset claude:0004-01-create-challenges
--comment 아티스트 원본 챌린지. status 없이 is_deleted 만 사용. view_count 만 BIGINT
CREATE TABLE challenges (
    challenge_seq     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    artist_seq        INTEGER      NOT NULL,
    song_seq          INTEGER      NOT NULL,
    description       TEXT         NOT NULL,
    video_key         VARCHAR(255) NOT NULL,
    thumbnail_key     VARCHAR(255) NOT NULL,
    duration_ms       INTEGER      NOT NULL,
    view_count        BIGINT       NOT NULL DEFAULT 0,
    participant_count INTEGER      NOT NULL DEFAULT 0,
    like_count        INTEGER      NOT NULL DEFAULT 0,
    comment_count     INTEGER      NOT NULL DEFAULT 0,
    reg_dttm          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm          TIMESTAMPTZ  NULL,
    is_deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_challenges PRIMARY KEY (challenge_seq),
    CONSTRAINT ck_challenges_duration          CHECK (duration_ms > 0),
    CONSTRAINT ck_challenges_view_count        CHECK (view_count >= 0),
    CONSTRAINT ck_challenges_participant_count CHECK (participant_count >= 0),
    CONSTRAINT ck_challenges_like_count        CHECK (like_count >= 0),
    CONSTRAINT ck_challenges_comment_count     CHECK (comment_count >= 0),
    CONSTRAINT fk_challenges_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_challenges_song FOREIGN KEY (song_seq)
        REFERENCES songs (song_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_challenges_feed ON challenges (is_deleted, reg_dttm DESC);
CREATE INDEX idx_challenges_song ON challenges (song_seq);
--rollback DROP TABLE challenges;

--changeset claude:0004-02-create-challenge-participants
--comment 추가 참여 아티스트 = 교체 가능 인물 슬롯. mask 는 단일 비트, 0 은 예약값
CREATE TABLE challenge_participants (
    challenge_seq        INTEGER NOT NULL,
    artist_seq           INTEGER NOT NULL,
    participant_mask     INTEGER NOT NULL,
    bbox_left_top_x      INTEGER NOT NULL,
    bbox_left_top_y      INTEGER NOT NULL,
    bbox_right_bottom_x  INTEGER NOT NULL,
    bbox_right_bottom_y  INTEGER NOT NULL,
    CONSTRAINT pk_challenge_participants PRIMARY KEY (challenge_seq, artist_seq),
    CONSTRAINT uq_challenge_participants_mask UNIQUE (challenge_seq, participant_mask),
    CONSTRAINT ck_challenge_participants_mask CHECK (
        participant_mask >= 0
        AND (participant_mask & (participant_mask - 1)) = 0
    ),
    CONSTRAINT ck_challenge_participants_bbox CHECK (
        bbox_left_top_x >= 0
        AND bbox_left_top_y >= 0
        AND bbox_right_bottom_x > bbox_left_top_x
        AND bbox_right_bottom_y > bbox_left_top_y
    ),
    CONSTRAINT fk_challenge_participants_challenge FOREIGN KEY (challenge_seq)
        REFERENCES challenges (challenge_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_challenge_participants_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT
);
--rollback DROP TABLE challenge_participants;

--changeset claude:0004-03-create-edited-challenges
