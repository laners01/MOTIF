    participant_mask     INTEGER      NOT NULL,
    video_key            VARCHAR(255) NOT NULL,
    initial_scene_key    VARCHAR(255) NOT NULL,
    reg_dttm             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm             TIMESTAMPTZ  NULL,
    CONSTRAINT pk_edited_challenges PRIMARY KEY (edited_challenge_seq),
    CONSTRAINT uq_edited_challenges_mask UNIQUE (challenge_seq, participant_mask),
    CONSTRAINT ck_edited_challenges_mask CHECK (participant_mask >= 0),
    CONSTRAINT fk_edited_challenges_challenge FOREIGN KEY (challenge_seq)
        REFERENCES challenges (challenge_seq) ON DELETE RESTRICT
);
