    CONSTRAINT uq_motif_asset_prices_asset_country UNIQUE (asset_seq, country_seq),
    CONSTRAINT ck_motif_asset_prices_amount CHECK (
        amount > 0
        AND currency ~ '^[A-Z]{3}$'
    ),
    CONSTRAINT fk_motif_asset_prices_asset FOREIGN KEY (asset_seq)
