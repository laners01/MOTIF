--changeset claude:0009-01-create-motif-assets
--comment 아티스트 영상 에셋. title 은 description 과 별개의 표시명(R6 신설)
CREATE TABLE motif_assets (
    asset_seq     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    artist_seq    INTEGER      NOT NULL,
    title         VARCHAR(100) NOT NULL,
    description   TEXT         NULL,
    video_key     VARCHAR(255) NOT NULL,
    thumbnail_key VARCHAR(255) NOT NULL,
    duration_ms   INTEGER      NOT NULL,
    asset_type    VARCHAR(10)  NOT NULL DEFAULT 'NORMAL',
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    reg_dttm      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ  NULL,
    CONSTRAINT pk_motif_assets PRIMARY KEY (asset_seq),
    CONSTRAINT ck_motif_assets_duration CHECK (duration_ms > 0),
    CONSTRAINT ck_motif_assets_type CHECK (asset_type IN ('NORMAL','PREMIUM','SECRET')),
    CONSTRAINT fk_motif_assets_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_motif_assets_artist ON motif_assets (artist_seq, is_active, reg_dttm DESC);
--rollback DROP TABLE motif_assets;

--changeset claude:0009-02-create-motif-asset-prices
--comment 에셋 국가별 현재 판매가. 가격 이력 테이블은 두지 않는다
CREATE TABLE motif_asset_prices (
    asset_price_seq INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    asset_seq       INTEGER       NOT NULL,
    country_seq     INTEGER       NOT NULL,
    amount          NUMERIC(10,2) NOT NULL,
    currency        CHAR(3)       NOT NULL,
    is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
    reg_usr_seq     INTEGER       NOT NULL,
    reg_dttm        TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq     INTEGER       NULL,
    mod_dttm        TIMESTAMPTZ   NULL,
