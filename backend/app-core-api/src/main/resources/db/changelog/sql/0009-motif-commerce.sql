--changeset claude:0009-04-create-orders
--comment 결제 시도 이력 원천. 삭제하지 않으며 가격 행 FK 대신 스냅샷을 저장한다
CREATE TABLE orders (
    order_seq            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    order_uuid           UUID          NOT NULL,
    user_seq             INTEGER       NOT NULL,
    product_type         VARCHAR(10)   NOT NULL,
    asset_seq            INTEGER       NULL,
    artist_seq           INTEGER       NULL,
    country_code         CHAR(2)       NOT NULL,
    pass_duration_months SMALLINT      NULL,
    amount               NUMERIC(10,2) NOT NULL,
    currency             CHAR(3)       NOT NULL,
    status               VARCHAR(12)   NOT NULL DEFAULT 'PENDING',
    payment_provider     VARCHAR(20)   NULL,
    payment_key          VARCHAR(200)  NULL,
    approved_dttm        TIMESTAMPTZ   NULL,
    fail_reason          VARCHAR(200)  NULL,
    expires_dttm         TIMESTAMPTZ   NOT NULL,
    reg_dttm             TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm             TIMESTAMPTZ   NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_seq),
    CONSTRAINT uq_orders_order_uuid UNIQUE (order_uuid),
    CONSTRAINT uq_orders_payment_provider_key UNIQUE (payment_provider, payment_key),
    CONSTRAINT ck_orders_product_type CHECK (product_type IN ('ASSET','PASS')),
    CONSTRAINT ck_orders_status CHECK (
        status IN ('PENDING','PAID','FAILED','EXPIRED','CANCELED','REFUNDED')
    ),
    CONSTRAINT ck_orders_product_shape CHECK (
        (
          product_type = 'ASSET'
          AND asset_seq IS NOT NULL
          AND artist_seq IS NULL
          AND pass_duration_months IS NULL
        )
        OR
        (
          product_type = 'PASS'
          AND artist_seq IS NOT NULL
          AND asset_seq IS NULL
          AND pass_duration_months IS NOT NULL
          AND pass_duration_months > 0
        )
    ),
    CONSTRAINT ck_orders_common CHECK (
        country_code ~ '^[A-Z]{2}$'
        AND currency ~ '^[A-Z]{3}$'
        AND amount > 0
        AND expires_dttm > reg_dttm
    ),
    CONSTRAINT ck_orders_payment_key_provider CHECK (
        payment_key IS NULL OR payment_provider IS NOT NULL
    ),
    CONSTRAINT ck_orders_status_shape CHECK (
        (
          status = 'PENDING'
          AND payment_key IS NULL
          AND approved_dttm IS NULL
          AND fail_reason IS NULL
        )
        OR
        (
          status = 'PAID'
          AND payment_provider IS NOT NULL
          AND payment_key IS NOT NULL
          AND approved_dttm IS NOT NULL
          AND fail_reason IS NULL
        )
        OR
        (
          status = 'FAILED'
          AND payment_provider IS NOT NULL
          AND approved_dttm IS NULL
          AND fail_reason IS NOT NULL
        )
        OR
        (
          status = 'EXPIRED'
          AND payment_key IS NULL
          AND approved_dttm IS NULL
          AND fail_reason IS NULL
        )
        OR
        (
          status = 'CANCELED'
          AND payment_key IS NULL
          AND approved_dttm IS NULL
          AND fail_reason IS NULL
        )
        OR
        (
          status = 'REFUNDED'
          AND payment_provider IS NOT NULL
          AND payment_key IS NOT NULL
          AND approved_dttm IS NOT NULL
          AND fail_reason IS NULL
        )
    ),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_asset FOREIGN KEY (asset_seq)
        REFERENCES motif_assets (asset_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_orders_user ON orders (user_seq, reg_dttm DESC);
--rollback DROP TABLE orders;

