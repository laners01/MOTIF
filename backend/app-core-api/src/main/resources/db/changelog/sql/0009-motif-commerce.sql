--changeset claude:0009-06-create-motif-passes
--comment 회원×아티스트당 1행. canceled_dttm 은 취소 의사 기록이며 이용 판정에 불참
CREATE TABLE motif_passes (
    pass_seq        INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    user_seq        INTEGER     NOT NULL,
    artist_seq      INTEGER     NOT NULL,
    order_seq       BIGINT      NOT NULL,
    duration_months SMALLINT    NOT NULL,
    started_dttm    TIMESTAMPTZ NOT NULL,
    expires_dttm    TIMESTAMPTZ NOT NULL,
    status          VARCHAR(12) NOT NULL DEFAULT 'ACTIVE',
    canceled_dttm   TIMESTAMPTZ NULL,
    reg_dttm        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm        TIMESTAMPTZ NULL,
    CONSTRAINT pk_motif_passes PRIMARY KEY (pass_seq),
    CONSTRAINT uq_motif_passes_user_artist UNIQUE (user_seq, artist_seq),
    CONSTRAINT uq_motif_passes_order UNIQUE (order_seq),
    CONSTRAINT ck_motif_passes_values CHECK (
        duration_months > 0
        AND expires_dttm > started_dttm
        AND status IN ('ACTIVE','EXPIRED','REFUNDED')
        AND (canceled_dttm IS NULL OR canceled_dttm >= started_dttm)
    ),
    CONSTRAINT fk_motif_passes_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_motif_passes_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_motif_passes_order FOREIGN KEY (order_seq)
        REFERENCES orders (order_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_motif_passes_user ON motif_passes (user_seq, status, expires_dttm DESC);
--rollback DROP TABLE motif_passes;
