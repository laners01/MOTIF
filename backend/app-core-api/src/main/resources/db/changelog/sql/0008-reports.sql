CREATE TABLE reports (
    report_seq            BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    reporter_seq          INTEGER     NOT NULL,
    video_seq             BIGINT      NULL,
    challenge_comment_seq BIGINT      NULL,
    video_comment_seq     BIGINT      NULL,
    notice_comment_seq    BIGINT      NULL,
    reason_code           VARCHAR(30) NOT NULL,
    status                VARCHAR(12) NOT NULL DEFAULT 'RECEIVED',
    processed_usr_seq     INTEGER     NULL,
    processed_dttm        TIMESTAMPTZ NULL,
    reg_dttm              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm              TIMESTAMPTZ NULL,
    CONSTRAINT pk_reports PRIMARY KEY (report_seq),
    CONSTRAINT uq_reports_reporter_video             UNIQUE (reporter_seq, video_seq),
    CONSTRAINT uq_reports_reporter_challenge_comment UNIQUE (reporter_seq, challenge_comment_seq),
    CONSTRAINT uq_reports_reporter_video_comment     UNIQUE (reporter_seq, video_comment_seq),
    CONSTRAINT uq_reports_reporter_notice_comment    UNIQUE (reporter_seq, notice_comment_seq),
    CONSTRAINT ck_reports_status CHECK (status IN ('RECEIVED','ACCEPTED','REJECTED')),
    CONSTRAINT ck_reports_exactly_one_target CHECK (
        (
          (video_seq IS NOT NULL)::int
        + (challenge_comment_seq IS NOT NULL)::int
        + (video_comment_seq IS NOT NULL)::int
        + (notice_comment_seq IS NOT NULL)::int
        ) = 1
    ),
    CONSTRAINT ck_reports_processed CHECK (
        (
          status = 'RECEIVED'
          AND processed_usr_seq IS NULL
          AND processed_dttm IS NULL
        )
        OR
        (
          status IN ('ACCEPTED','REJECTED')
          AND processed_usr_seq IS NOT NULL
          AND processed_dttm IS NOT NULL
        )
    ),
    CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_video FOREIGN KEY (video_seq)
        REFERENCES participation_videos (video_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_challenge_comment FOREIGN KEY (challenge_comment_seq)
        REFERENCES challenge_comments (challenge_comment_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_video_comment FOREIGN KEY (video_comment_seq)
        REFERENCES video_comments (video_comment_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_notice_comment FOREIGN KEY (notice_comment_seq)
        REFERENCES notice_comments (notice_comment_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_processed_usr FOREIGN KEY (processed_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_reports_status ON reports (status, reg_dttm);
