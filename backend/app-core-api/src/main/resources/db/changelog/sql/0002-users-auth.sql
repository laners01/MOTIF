--rollback DROP TABLE admins;

--changeset claude:0002-05-create-refresh-tokens
--comment 기기별 로그인 유지·rotation. 활성 토큰 부분 인덱스는 0012
CREATE TABLE refresh_tokens (
    token_seq      BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_seq       INTEGER     NOT NULL,
    token_hash     CHAR(64)    NOT NULL,
    expires_dttm   TIMESTAMPTZ NOT NULL,
    revoked_dttm   TIMESTAMPTZ NULL,
    last_used_dttm TIMESTAMPTZ NULL,
    reg_dttm       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (token_seq),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_expires CHECK (expires_dttm > reg_dttm),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_seq, expires_dttm DESC);
--rollback DROP TABLE refresh_tokens;

