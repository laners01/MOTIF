--changeset claude:0002-01-create-users
--comment 모든 서비스 행위 주체. rep_motif_result_seq 는 순환 참조 방지로 FK 미적용(논리 참조)
CREATE TABLE users (
    user_seq             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nickname             VARCHAR(50)  NOT NULL,
    profile_image_key    VARCHAR(255) NULL,
    rep_motif_result_seq BIGINT       NULL,
    role                 VARCHAR(10)  NOT NULL,
    is_deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_dttm             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm             TIMESTAMPTZ  NULL,
    mod_usr_seq          INTEGER      NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_seq),
    CONSTRAINT ck_users_role CHECK (role IN ('USER','ARTIST','ADMIN')),
    CONSTRAINT ck_users_nickname_length CHECK (char_length(nickname) BETWEEN 1 AND 50),
    CONSTRAINT fk_users_mod_usr FOREIGN KEY (mod_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
--rollback DROP TABLE users;

--changeset claude:0002-02-create-user-accounts
--comment 인증 계정 상태. user 당 1개(1:1)
CREATE TABLE user_accounts (
    account_seq    INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    user_seq       INTEGER     NOT NULL,
    account_status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE',
    reg_dttm       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm       TIMESTAMPTZ NULL,
    CONSTRAINT pk_user_accounts PRIMARY KEY (account_seq),
    CONSTRAINT uq_user_accounts_user UNIQUE (user_seq),
    CONSTRAINT ck_user_accounts_status CHECK (account_status IN ('ACTIVE','SUSPENDED')),
    CONSTRAINT fk_user_accounts_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
--rollback DROP TABLE user_accounts;

--changeset claude:0002-03-create-user-oauth-accounts
--comment 서비스 계정 ↔ OAuth 제공자 계정 연결
CREATE TABLE user_oauth_accounts (
    oauth_account_seq INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    account_seq       INTEGER      NOT NULL,
    provider_seq      INTEGER      NOT NULL,
    oauth_subject     VARCHAR(255) NOT NULL,
    reg_dttm          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_oauth_accounts PRIMARY KEY (oauth_account_seq),
    CONSTRAINT uq_user_oauth_account_provider UNIQUE (account_seq, provider_seq),
    CONSTRAINT uq_user_oauth_subject UNIQUE (provider_seq, oauth_subject),
    CONSTRAINT fk_user_oauth_accounts_account FOREIGN KEY (account_seq)
        REFERENCES user_accounts (account_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_user_oauth_accounts_provider FOREIGN KEY (provider_seq)
        REFERENCES oauth_providers (provider_seq) ON DELETE RESTRICT
);
--rollback DROP TABLE user_oauth_accounts;

--changeset claude:0002-04-create-admins
--comment 시연용 백오피스 로그인 전용. users 와 관계를 두지 않는다
CREATE TABLE admins (
