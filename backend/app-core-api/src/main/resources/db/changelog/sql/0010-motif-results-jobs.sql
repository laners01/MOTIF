CREATE TABLE composite_jobs (
    job_seq              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    job_uuid             UUID         NOT NULL,
    job_type             VARCHAR(10)  NOT NULL,
    user_seq             INTEGER      NOT NULL,
    challenge_seq        INTEGER      NULL,
    asset_seq            INTEGER      NULL,
    edited_challenge_seq INTEGER      NULL,
    raw_video_key        VARCHAR(255) NOT NULL,
    correction_enabled   BOOLEAN      NOT NULL DEFAULT TRUE,
    status               VARCHAR(12)  NOT NULL DEFAULT 'UPLOADED',
    fail_code            VARCHAR(30)  NULL,
    result_video_key     VARCHAR(255) NULL,
    result_thumbnail_key VARCHAR(255) NULL,
    attempt              SMALLINT     NOT NULL DEFAULT 1,
    processing_ms        INTEGER      NULL,
    reg_dttm             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm             TIMESTAMPTZ  NULL,
    CONSTRAINT pk_composite_jobs PRIMARY KEY (job_seq),
    CONSTRAINT uq_composite_jobs_job_uuid UNIQUE (job_uuid),
    CONSTRAINT ck_composite_jobs_type_value CHECK (job_type IN ('CHALLENGE','MOTIF')),
    CONSTRAINT ck_composite_jobs_status_value CHECK (
        status IN ('UPLOADED','QUEUED','PROCESSING','DONE','FAILED')
    ),
    CONSTRAINT ck_composite_jobs_type_shape CHECK (
        (
          job_type = 'CHALLENGE'
          AND challenge_seq IS NOT NULL
          AND asset_seq IS NULL
        )
        OR
        (
          job_type = 'MOTIF'
          AND asset_seq IS NOT NULL
          AND challenge_seq IS NULL
          AND edited_challenge_seq IS NULL
        )
    ),
    CONSTRAINT ck_composite_jobs_status_shape CHECK (
        (
          status = 'DONE'
          AND result_video_key IS NOT NULL
          AND result_thumbnail_key IS NOT NULL
          AND fail_code IS NULL
        )
        OR
        (
          status = 'FAILED'
          AND fail_code IS NOT NULL
          AND result_video_key IS NULL
          AND result_thumbnail_key IS NULL
        )
        OR
        (
          status IN ('UPLOADED','QUEUED','PROCESSING')
          AND fail_code IS NULL
          AND result_video_key IS NULL
          AND result_thumbnail_key IS NULL
        )
    ),
    CONSTRAINT ck_composite_jobs_attempt CHECK (
        attempt >= 1
        AND (processing_ms IS NULL OR processing_ms >= 0)
    ),
    CONSTRAINT fk_composite_jobs_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_composite_jobs_challenge FOREIGN KEY (challenge_seq)
        REFERENCES challenges (challenge_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_composite_jobs_asset FOREIGN KEY (asset_seq)
        REFERENCES motif_assets (asset_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_composite_jobs_edited_challenge FOREIGN KEY (edited_challenge_seq)
        REFERENCES edited_challenges (edited_challenge_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_composite_jobs_user ON composite_jobs (user_seq, reg_dttm DESC);
--rollback DROP TABLE composite_jobs;

--changeset claude:0010-02-create-motif-results
--comment 성공 MOTIF 잡의 결과물 보관함. uq_motif_results_job 이 멱등 생성의 근거. mod_dttm 은 v0.15 Q2 보정분
CREATE TABLE motif_results (
    result_seq    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_seq      INTEGER      NOT NULL,
    asset_seq     INTEGER      NOT NULL,
    artist_seq    INTEGER      NOT NULL,
    job_seq       BIGINT       NOT NULL,
    video_key     VARCHAR(255) NOT NULL,
    thumbnail_key VARCHAR(255) NOT NULL,
    duration_ms   INTEGER      NOT NULL,
    description   TEXT         NULL,
    reg_dttm      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ  NULL,
    is_deleted    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_motif_results PRIMARY KEY (result_seq),
    CONSTRAINT uq_motif_results_job UNIQUE (job_seq),
    CONSTRAINT ck_motif_results_duration CHECK (duration_ms > 0),
    CONSTRAINT fk_motif_results_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_motif_results_asset FOREIGN KEY (asset_seq)
        REFERENCES motif_assets (asset_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_motif_results_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_motif_results_job FOREIGN KEY (job_seq)
        REFERENCES composite_jobs (job_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_motif_results_user        ON motif_results (user_seq, is_deleted, reg_dttm DESC);
CREATE INDEX idx_motif_results_asset       ON motif_results (asset_seq, is_deleted, reg_dttm DESC);
CREATE INDEX idx_motif_results_user_artist ON motif_results (user_seq, artist_seq, is_deleted, reg_dttm DESC);
--rollback DROP TABLE motif_results;

