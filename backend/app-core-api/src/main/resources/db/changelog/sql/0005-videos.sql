--comment 사용자 합성·게시 영상. view_count 만 BIGINT, 나머지 카운터는 INTEGER
CREATE TABLE participation_videos (
    video_seq          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    challenge_seq      INTEGER      NOT NULL,
    artist_seq         INTEGER      NOT NULL,
    user_seq           INTEGER      NOT NULL,
    job_seq            BIGINT       NOT NULL,
    description        TEXT         NOT NULL,
    video_key          VARCHAR(255) NOT NULL,
    thumbnail_key      VARCHAR(255) NOT NULL,
    duration_ms        INTEGER      NOT NULL,
    visibility         VARCHAR(10)  NOT NULL DEFAULT 'PUBLIC',
    comment_enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    view_count         BIGINT       NOT NULL DEFAULT 0,
    like_count         INTEGER      NOT NULL DEFAULT 0,
    comment_count      INTEGER      NOT NULL DEFAULT 0,
    has_artist_like    BOOLEAN      NOT NULL DEFAULT FALSE,
    has_artist_comment BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_dttm           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm           TIMESTAMPTZ  NULL,
    mod_usr_seq        INTEGER      NULL,
    is_deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_participation_videos PRIMARY KEY (video_seq),
    CONSTRAINT uq_participation_videos_job UNIQUE (job_seq),
    CONSTRAINT ck_pv_duration      CHECK (duration_ms > 0),
    CONSTRAINT ck_pv_visibility    CHECK (visibility IN ('PUBLIC','PRIVATE')),
    CONSTRAINT ck_pv_view_count    CHECK (view_count >= 0),
    CONSTRAINT ck_pv_like_count    CHECK (like_count >= 0),
    CONSTRAINT ck_pv_comment_count CHECK (comment_count >= 0),
    CONSTRAINT fk_pv_challenge FOREIGN KEY (challenge_seq)
        REFERENCES challenges (challenge_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_pv_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_pv_user FOREIGN KEY (user_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_pv_mod_usr FOREIGN KEY (mod_usr_seq)
        REFERENCES users (user_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_pv_challenge_feed ON participation_videos (challenge_seq, visibility, is_deleted, like_count DESC);
CREATE INDEX idx_pv_artist_feed    ON participation_videos (artist_seq, visibility, is_deleted, reg_dttm DESC);
CREATE INDEX idx_pv_user           ON participation_videos (user_seq, is_deleted, reg_dttm DESC);
CREATE INDEX idx_pv_user_artist    ON participation_videos (user_seq, artist_seq, is_deleted);
--rollback DROP TABLE participation_videos;

