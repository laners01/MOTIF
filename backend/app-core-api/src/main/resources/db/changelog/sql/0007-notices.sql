--changeset claude:0007-01-create-notices
--comment 아티스트 공지. 최신순 조회, 구독자 팬아웃은 subscriptions 직접 조회
CREATE TABLE notices (
    notice_seq    INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    artist_seq    INTEGER     NOT NULL,
    content       TEXT        NOT NULL,
    like_count    INTEGER     NOT NULL DEFAULT 0,
    comment_count INTEGER     NOT NULL DEFAULT 0,
    reg_dttm      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ NULL,
    is_deleted    BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_notices PRIMARY KEY (notice_seq),
    CONSTRAINT ck_notices_like_count    CHECK (like_count >= 0),
    CONSTRAINT ck_notices_comment_count CHECK (comment_count >= 0),
    CONSTRAINT fk_notices_artist FOREIGN KEY (artist_seq)
        REFERENCES artists (artist_seq) ON DELETE RESTRICT
);
CREATE INDEX idx_notices_artist ON notices (artist_seq, is_deleted, reg_dttm DESC);
--rollback DROP TABLE notices;

