CREATE TABLE device_tokens (
    token_seq      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    user_seq       INTEGER      NOT NULL,
    fcm_token      VARCHAR(255) NOT NULL,
    platform       VARCHAR(10)  NOT NULL DEFAULT 'ANDROID',
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    last_used_dttm TIMESTAMPTZ  NULL,
    reg_dttm       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm       TIMESTAMPTZ  NULL,
    CONSTRAINT pk_device_tokens PRIMARY KEY (token_seq),
    CONSTRAINT uq_device_tokens_fcm_token UNIQUE (fcm_token),
    CONSTRAINT ck_device_tokens_platform CHECK (platform IN ('ANDROID','IOS','WEB'))
);
CREATE INDEX idx_device_tokens_user_active ON device_tokens (user_seq, is_active);
